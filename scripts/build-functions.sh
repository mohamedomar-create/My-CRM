#!/usr/bin/env bash
# Bundles each server function with the shared engine into one file Supabase can deploy (supabase/functions/<name>/index.ts).
set -euo pipefail
cd "$(dirname "$0")/.."
for src in supabase/functions/*/source.ts; do
  dir=$(dirname "$src")
  out="$dir/index.ts"
  bun build "$src" --target=browser --format=esm --minify --external 'npm:*' --outfile "$out.tmp" >/dev/null
  { echo "// @ts-nocheck"; echo "// GENERATED by scripts/build-functions.sh from source.ts and src/lib. Do not edit by hand."; cat "$out.tmp"; } > "$out"
  rm "$out.tmp"
  echo "built $out ($(wc -c < "$out") bytes)"
done
